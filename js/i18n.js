let current = 'es';

export function getLang() {
  return current;
}

export function t(key, vars) {
  const table = dict[current] || dict.es;
  let text = table[key] ?? dict.es[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.split(`{${name}}`).join(String(value));
    }
  }
  return text;
}

export function setLang(lang) {
  current = LANGUAGES.includes(lang) ? lang : 'es';
  document.documentElement.lang = current === 'zh' ? 'zh-CN' : current;
  applyStatic();
  return current;
}

/** Traduce nodos con data-i18n / data-i18n-placeholder / data-i18n-title / data-i18n-aria. */
export function applyStatic(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((node) => {
    const key = node.getAttribute('data-i18n');
    if (key) node.textContent = t(key);
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((node) => {
    node.setAttribute('placeholder', t(node.getAttribute('data-i18n-placeholder')));
  });
  root.querySelectorAll('[data-i18n-title]').forEach((node) => {
    node.setAttribute('title', t(node.getAttribute('data-i18n-title')));
  });
  root.querySelectorAll('[data-i18n-aria]').forEach((node) => {
    node.setAttribute('aria-label', t(node.getAttribute('data-i18n-aria')));
  });
  const title = t('doc.title');
  if (title) document.title = `${title} 1.1.0`;
}
